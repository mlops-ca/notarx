package mysqlbaseline

import (
	"fmt"
	"slices"
	"strings"
)

// docHeader opens docs/mysql-schema-decisions.md.
const docHeader = `# MySQL schema decisions

[Documentation index](README.md)

Generated by ~go run ./tools/mysqlbaseline~ from ~migrations/catalogue.yaml~ and
~migrations/mysql-decisions.yaml~. Do not edit by hand: ~make test~ fails when this file differs
from what the generator produces. These are the per-column, per-index and per-trigger decisions
that [ADR 0022](adr/0022-database-portability-mysql-heatwave.md) asks for when the MySQL 8.4
baseline (~migrations/mysql/000001_baseline.sql~) is generated from the PostgreSQL schema.

## Rules

- UUID columns are ~CHAR(36)~ with the ~ascii_bin~ collation; identifiers are generated by the
  application as UUIDv7.
- Every table and every other text column use ~utf8mb4_0900_bin~, so ~Admin~ and ~admin~ are two
  values. No column uses an ~ai_ci~ collation, so the parity allow-list of such columns is empty.
- A text column that appears in a key or an index is a bounded ~VARCHAR~ (4 bytes per character
  against the 3072-byte InnoDB key limit); any other text column is ~TEXT~. The generator fails when a key
  exceeds the limit.
- A text value too long to index stays in ~TEXT~ and is keyed by a stored ~<column>_sha256 BINARY(32)~
  column, which the schema parity check maps back to the original column.
- ~timestamptz~ is ~DATETIME(6)~ in UTC, ~jsonb~ is ~JSON~, ~boolean~ is ~TINYINT(1)~, ~bytea~ is
  ~LONGBLOB~ (~VARBINARY(64)~ where keyed), ~numeric~ is ~DECIMAL(20,10)~, a sequence default is
  ~AUTO_INCREMENT~.
- Foreign keys are added after all tables, with the same actions as PostgreSQL.
- CHECK constraints are translated by the parser in ~internal/mysqlbaseline/translate.go~; one it
  cannot translate needs an explicit decision, so none is dropped silently.
- No trigram index. A partial index becomes a full index; a partial unique index becomes a unique
  index over a generated column that is NULL outside the predicate; queue-claim indexes lead with a
  generated flag column (ADR 0023 section 5).
- ~notarx_lock_buckets~ holds 4096 rows for ~Locker.LockTx~.
`

func (g *generator) doc() string {
	var b strings.Builder
	b.WriteString(strings.ReplaceAll(docHeader, "~", "`"))
	section := func(title, intro, tableHeader string, rows []string) {
		b.WriteString("\n## " + title + "\n\n" + intro + "\n")
		if len(rows) == 0 {
			b.WriteString("\nNone.\n")
			return
		}
		b.WriteString("\n" + tableHeader + "\n")
		for _, row := range slices.Sorted(slices.Values(rows)) {
			b.WriteString(row + "\n")
		}
	}

	var arrays []string
	for _, key := range slices.Sorted(mapKeys(g.decisions.Arrays)) {
		table, column, _ := strings.Cut(key, ".")
		arrays = append(arrays, fmt.Sprintf("| %s | %s | JSON | %s |", table, column, g.decisions.Arrays[key]))
	}
	section("TEXT[] columns", "Every PostgreSQL array column is a JSON array: no query filters by element except where the reason says otherwise.",
		"| Table | Column | MySQL | Reason |\n| --- | --- | --- | --- |", arrays)

	var widths []string
	for _, name := range slices.Sorted(mapKeys(g.decisions.KeyWidths)) {
		widths = append(widths, fmt.Sprintf("| %s | %d |", name, g.decisions.KeyWidths[name]))
	}
	fmt.Fprintf(&b, "\n## Key column widths\n\nAn indexed text column is `VARCHAR(%d)` unless its name is listed here or it has an exception below.\n", g.decisions.DefaultKeyWidth)
	if len(widths) > 0 {
		b.WriteString("\n| Column name | VARCHAR width |\n| --- | --- |\n" + strings.Join(widths, "\n") + "\n")
	}
	var exceptions []string
	for _, key := range slices.Sorted(mapKeys(g.decisions.Columns)) {
		d := g.decisions.Columns[key]
		switch {
		case d.Hash || d.Width == 0 && d.Type == "":
		case d.Width > 0:
			exceptions = append(exceptions, fmt.Sprintf("| %s | VARCHAR(%d) | %s |", key, d.Width, d.Reason))
		default:
			exceptions = append(exceptions, fmt.Sprintf("| %s | %s | %s |", key, d.Type, d.Reason))
		}
	}
	if len(exceptions) > 0 {
		b.WriteString("\n| Column | MySQL type | Reason |\n| --- | --- | --- |\n" + strings.Join(exceptions, "\n") + "\n")
	}

	section("Hashed keys", "Long text keys: the value stays in TEXT and a stored SHA-256 column carries the key.",
		"| Column | Reason |\n| --- | --- |", g.report.hashColumns)
	section("Special indexes", "Every PostgreSQL partial, expression, trigram or operator-class index and what MySQL gets instead.",
		"| Table | Index | MySQL | Reason |\n| --- | --- | --- | --- |", g.report.indexActions)
	section("CHECK constraints not ported", "Constraints skipped by decision; every other CHECK constraint of the catalogue is created.",
		"| Table | Constraint | Reason |\n| --- | --- | --- |", g.report.skippedChecks)
	section("CHECK constraints refused by MySQL", "MySQL rejects a CHECK on a column that a foreign key action rewrites, so the generator leaves these out and the store validates the value.",
		"| Table | Constraint | Reason |\n| --- | --- | --- |", g.report.autoSkipped)

	var triggers []string
	for _, name := range slices.Sorted(mapKeys(g.catalogue.Triggers)) {
		d := g.decisions.Triggers[name]
		table, _, _ := strings.Cut(g.catalogue.Triggers[name], ":")
		triggers = append(triggers, fmt.Sprintf("| %s | %s | %s | %s |", table, name, d.Disposition, d.Reason))
	}
	section("Triggers", "Each PostgreSQL trigger is dropped (polling or counters replace it), ported to application code, or kept as a MySQL trigger.",
		"| Table | Trigger | Disposition | Reason |\n| --- | --- | --- | --- |", triggers)

	var views []string
	for _, name := range g.catalogue.Views {
		d := g.decisions.Views[name]
		views = append(views, fmt.Sprintf("| %s | %s | %s |", name, d.Disposition, d.Reason))
	}
	section("Views", "PostgreSQL views the MySQL baseline does not create.", "| View | Disposition | Reason |\n| --- | --- | --- |", views)

	var partitioned []string
	for _, name := range g.report.partitioned {
		partitioned = append(partitioned, "| "+name+" | range-partitioned | plain InnoDB table, pruned by primary-key range deletes |")
	}
	section("Partitioned tables", "Partitioning is PostgreSQL only (ADR 0023): the keys are the same.", "| Table | PostgreSQL | MySQL |\n| --- | --- | --- |", partitioned)

	var seeds []string
	for _, name := range g.report.seedTables {
		seeds = append(seeds, fmt.Sprintf("| %s | %d |", name, len(g.catalogue.Seeds[name])))
	}
	section("Seed rows", "Rows a freshly migrated database holds, besides the 4096 lock buckets.", "| Table | Rows |\n| --- | --- |", seeds)
	return b.String()
}
