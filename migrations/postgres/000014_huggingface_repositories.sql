-- ADR 0027 slice 3: Hugging Face model and dataset repositories. The format joins the format checks of repositories
-- and groups; the five hf_* tables hold repositories, commits, per-commit file rows, the digests a repository holds
-- and the mutable refs (branch, tag) with their revalidation time.
--
-- Every key column is bounded so the tables port to MySQL (ADR 0022): no TEXT in a key, path is VARCHAR(512)
-- (2048 bytes in utf8mb4_0900_bin, inside the 3072-byte key limit with the 36-byte commit id), longer paths are
-- rejected in Go (path_too_long). Ids are UUIDv7 generated by the application (internal/ids, ADR 0023 section 4).
-- No foreign key points into a partitioned table; hf_files and hf_commits are bounded by NOTARX_HF_MAX_FILES_PER_COMMIT
-- and the retention janitor rather than partitioned.
ALTER TABLE public.hosted_repositories
    DROP CONSTRAINT hosted_repositories_format_check,
    ADD CONSTRAINT hosted_repositories_format_check CHECK ((format = ANY (ARRAY['raw'::text, 'oci'::text, 'maven'::text, 'conan'::text, 'npm'::text, 'pypi'::text, 'go'::text, 'apt'::text, 'cargo'::text, 'nuget'::text, 'helm'::text, 'rubygems'::text, 'huggingface'::text])));
ALTER TABLE public.hosted_groups
    DROP CONSTRAINT hosted_groups_format_check,
    ADD CONSTRAINT hosted_groups_format_check CHECK ((format = ANY (ARRAY['raw'::text, 'oci'::text, 'maven'::text, 'conan'::text, 'npm'::text, 'pypi'::text, 'go'::text, 'apt'::text, 'cargo'::text, 'nuget'::text, 'helm'::text, 'huggingface'::text])));

-- One row per Hugging Face repo id (org/name) of a notarx repository.
CREATE TABLE public.hf_repos (
    id uuid NOT NULL,
    repository_id uuid NOT NULL,
    repo_type character varying(16) NOT NULL,
    repo_name character varying(255) NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT hf_repos_pkey PRIMARY KEY (id),
    CONSTRAINT hf_repos_identity_key UNIQUE (repository_id, repo_type, repo_name),
    CONSTRAINT hf_repos_repository_id_fkey FOREIGN KEY (repository_id) REFERENCES public.hosted_repositories(id),
    CONSTRAINT hf_repos_repo_type_check CHECK (((repo_type)::text = ANY (ARRAY['model'::text, 'dataset'::text])))
);

-- An immutable commit. file_count and total_bytes stay NULL until the tree of the commit has been ingested (the tree
-- is fetched lazily, on the first request for it), so a commit with an empty tree is told apart from one not yet read.
CREATE TABLE public.hf_commits (
    id uuid NOT NULL,
    hf_repo_id uuid NOT NULL,
    commit_sha character(40) NOT NULL,
    parent_sha character(40),
    message text,
    author text,
    committed_at timestamp with time zone NOT NULL,
    source character varying(16) NOT NULL,
    file_count integer,
    total_bytes bigint,
    last_read_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT hf_commits_pkey PRIMARY KEY (id),
    CONSTRAINT hf_commits_identity_key UNIQUE (hf_repo_id, commit_sha),
    CONSTRAINT hf_commits_hf_repo_id_fkey FOREIGN KEY (hf_repo_id) REFERENCES public.hf_repos(id) ON DELETE CASCADE,
    CONSTRAINT hf_commits_sha_check CHECK ((commit_sha ~ '^[0-9a-f]{40}$'::text)),
    CONSTRAINT hf_commits_parent_check CHECK (((parent_sha IS NULL) OR (parent_sha ~ '^[0-9a-f]{40}$'::text))),
    CONSTRAINT hf_commits_source_check CHECK (((source)::text = ANY (ARRAY['upstream'::text, 'hosted'::text, 'promoted'::text]))),
    CONSTRAINT hf_commits_counts_check CHECK ((((file_count IS NULL) OR (file_count >= 0)) AND ((total_bytes IS NULL) OR (total_bytes >= 0))))
);
CREATE INDEX hf_commits_repo_committed_idx ON public.hf_commits USING btree (hf_repo_id, committed_at DESC, id DESC);
CREATE INDEX hf_commits_last_read_idx ON public.hf_commits USING btree (last_read_at);

-- One row per file per commit. sha256 is NULL for a regular (non-LFS) file until its bytes have been read: the Hub
-- tree names such a file by its git blob id only.
CREATE TABLE public.hf_files (
    commit_id uuid NOT NULL,
    path character varying(512) NOT NULL,
    size bigint NOT NULL,
    sha256 character(64),
    lfs boolean DEFAULT false NOT NULL,
    git_blob_id character(40),
    pickle_flag boolean DEFAULT false NOT NULL,
    cached boolean DEFAULT false NOT NULL,
    CONSTRAINT hf_files_pkey PRIMARY KEY (commit_id, path),
    CONSTRAINT hf_files_commit_id_fkey FOREIGN KEY (commit_id) REFERENCES public.hf_commits(id) ON DELETE CASCADE,
    CONSTRAINT hf_files_size_check CHECK ((size >= 0)),
    CONSTRAINT hf_files_sha256_check CHECK (((sha256 IS NULL) OR (sha256 ~ '^[0-9a-f]{64}$'::text)))
);
CREATE INDEX hf_files_sha256_idx ON public.hf_files USING btree (sha256);

-- The distinct digests a repository holds; a digest counts once per repository in repository_usage_counters.
CREATE TABLE public.hf_blobs (
    hf_repo_id uuid NOT NULL,
    sha256 character(64) NOT NULL,
    size bigint NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT hf_blobs_pkey PRIMARY KEY (hf_repo_id, sha256),
    CONSTRAINT hf_blobs_hf_repo_id_fkey FOREIGN KEY (hf_repo_id) REFERENCES public.hf_repos(id) ON DELETE CASCADE,
    CONSTRAINT hf_blobs_size_check CHECK ((size >= 0)),
    CONSTRAINT hf_blobs_sha256_check CHECK ((sha256 ~ '^[0-9a-f]{64}$'::text))
);
CREATE INDEX hf_blobs_sha256_idx ON public.hf_blobs USING btree (sha256);

-- Mutable refs and the time they were last checked against upstream.
CREATE TABLE public.hf_refs (
    hf_repo_id uuid NOT NULL,
    ref_kind character varying(8) NOT NULL,
    ref_name character varying(255) NOT NULL,
    commit_sha character(40) NOT NULL,
    checked_at timestamp with time zone NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    CONSTRAINT hf_refs_pkey PRIMARY KEY (hf_repo_id, ref_kind, ref_name),
    CONSTRAINT hf_refs_hf_repo_id_fkey FOREIGN KEY (hf_repo_id) REFERENCES public.hf_repos(id) ON DELETE CASCADE,
    CONSTRAINT hf_refs_kind_check CHECK (((ref_kind)::text = ANY (ARRAY['branch'::text, 'tag'::text]))),
    CONSTRAINT hf_refs_sha_check CHECK ((commit_sha ~ '^[0-9a-f]{40}$'::text))
);
CREATE INDEX hf_refs_expires_idx ON public.hf_refs USING btree (expires_at);
