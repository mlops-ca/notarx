#!/usr/bin/env bash
# Derives internal/config/legacy_env.go: the closed list of legacy environment
# variable names that the pre-rename loader read (ADR 0013, slice 4).
#
# Usage: scripts/derive-legacy-env.sh [git-ref] > internal/config/legacy_env.go
#
# The default ref is the last commit before the GATEWAY_ -> NOTARX_ rename. The
# list is every legacy-prefixed name that appears in non-test Go source under
# cmd/ and internal/ at that ref (names ending in an underscore are prefix
# fragments, not settings, and are skipped). It is a closed list, not a prefix
# match: an unrelated variable with the same prefix stays harmless.
set -euo pipefail

ref=${1:-${LEGACY_ENV_REF:-b35c4a53}}
legacy_prefix="GATEWAY""_"
new_prefix="NOTARX""_"

names=$(git grep -ohE "${legacy_prefix}[A-Z0-9_]*[A-Z0-9]" "$ref" -- 'cmd/*.go' 'internal/*.go' ':!*_test.go' | sort -u)
if [[ -z "$names" ]]; then
  echo "no legacy environment names found at $ref" >&2
  exit 1
fi

{
cat <<EOF
// Code generated by scripts/derive-legacy-env.sh $ref; DO NOT EDIT.

package config

// legacyEnvNames is the closed list of environment variable names the
// pre-rename loader read, mapped to their NOTARX_ replacement. ADR 0013:
// no aliases and no fallback reads; the list exists only so startup can refuse.
var legacyEnvNames = map[string]string{
EOF
while IFS= read -r name; do
  printf '\t"%s": "%s",\n' "$name" "${new_prefix}${name#"$legacy_prefix"}"
done <<<"$names"
echo "}"
} | gofmt
